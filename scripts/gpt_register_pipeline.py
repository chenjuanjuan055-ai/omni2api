def log(*a):
    print(*a, flush=True)


def new_session() -> requests.Session:
    s = requests.Session()
    s.trust_env = False
    s.headers.update({"User-Agent": UA_CHROME})
    return s


# ---------------------------------------------------------------- 1. 出口
def gen_outlets(out: pathlib.Path, base_port: int, email_filter: str = "") -> list[dict]:
    import yaml
    sys.path.insert(0, str(REPO / "scripts"))
    from outlets_from_vvcloud import parse_subscription, to_mihomo, INFO_NAME_RE

    s = new_session()
    accounts = s.get(f"{CONSOLE}/api/accounts", timeout=30).json().get("data") or []
    if email_filter:
        accounts = [a for a in accounts if email_filter in str(a.get("email"))]
    log(f"[1] 控制台账号 {len(accounts)}")

    all_meta = []
    for a in accounts:
        url = a.get("subscribe_url")
        if not url:
            continue
        try:
            r = s.get(url, headers={"User-Agent": "v2rayN/6.0"}, timeout=30)
            text = r.text or ""
        except Exception as e:
            log(f"    {a.get('email')} 拉取失败: {type(e).__name__}")
            continue
        nodes = [n for n in parse_subscription(text) if not INFO_NAME_RE.search(n["name"])]
        proxies = to_mihomo(nodes)
        log(f"    {a.get('email'):<40} 有效节点 {len(proxies)}")
        for p in proxies:
            all_meta.append({"account": a.get("email"), "proxy": p})
    if not all_meta:
        raise SystemExit("没有可用节点")

    proxies = [m["proxy"] for m in all_meta]
    for i, p in enumerate(proxies):
        acct = all_meta[i]["account"].split("@")[0][:16]
        p["name"] = f"{i:03d}|{acct}|{p['name'].split('|', 1)[-1][:38]}"
    listeners = [{"name": f"vv-{base_port + i}", "type": "mixed", "port": base_port + i,
                  "listen": "127.0.0.1", "proxy": p["name"]} for i, p in enumerate(proxies)]
    cfg = {
        "mixed-port": base_port - 100, "allow-lan": False, "mode": "rule",
        "log-level": "warning", "ipv6": False,
        "external-controller": f"127.0.0.1:{base_port - 99}",
        "dns": {"enable": True, "ipv6": False, "listen": f"127.0.0.1:{base_port - 47}",
                "nameserver": ["223.5.5.5", "119.29.29.29"]},
        "proxies": proxies, "listeners": listeners, "rules": ["MATCH,DIRECT"],
    }
    out.mkdir(parents=True, exist_ok=True)
    (out / "config.yaml").write_text("# generated by gpt_register_pipeline.py\n"
                                     + yaml.safe_dump(cfg, allow_unicode=True, sort_keys=False),
                                     encoding="utf-8")
    meta = [{"port": base_port + i, "name": p["name"], "type": p["type"],
             "server": p["server"], "account": all_meta[i]["account"],
             "remark": p["name"].split("|", 2)[-1]} for i, p in enumerate(proxies)]
    (out / "ports.json").write_text(json.dumps(meta, ensure_ascii=False, indent=1), encoding="utf-8")
    log(f"[1] 生成 {len(proxies)} 个出口，端口 {base_port}-{base_port + len(proxies) - 1}")
    return meta


def start_mihomo(out: pathlib.Path):
    geo = pathlib.Path(r"D:\xi\Ai\smart-proxy\reg-exits")
    for f in ("geoip.dat", "geosite.dat"):
        if (geo / f).exists() and not (out / f).exists():
            shutil.copy2(geo / f, out / f)
    p = subprocess.Popen([MIHOMO, "-d", str(out), "-f", str(out / "config.yaml")],
                         stdout=open(out / "m.out.log", "ab"), stderr=open(out / "m.err.log", "ab"),
                         creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    time.sleep(5)
    log(f"[1] mihomo PID={p.pid} alive={p.poll() is None}")
    return p


# ---------------------------------------------------------------- 2. 探测
def probe(meta: list[dict], workers: int = 24, only_kw: str = "美国") -> list[dict]:
    s = new_session()

    def one(m):
        port = m["port"]
        px = {"http": f"http://127.0.0.1:{port}", "https": f"http://127.0.0.1:{port}"}
        rec = dict(m)
        try:
            g = s.get("https://ipwho.is/", proxies=px, timeout=15).json()
            if not g.get("success"):
                return rec
            c = g.get("connection") or {}
            rec.update(ip=g.get("ip"), country=g.get("country_code"), isp=c.get("isp"),
                       org=c.get("org"))
        except Exception:
            return rec
        try:
            r2 = s.get("https://auth.openai.com/oauth/authorize", proxies=px, timeout=20,
                       allow_redirects=False)
            rec["auth"] = r2.status_code
            rec["cf_pass"] = r2.status_code != 403
        except Exception:
            rec["auth"] = "ERR"
        return rec

    pick = [m for m in meta if only_kw in (m.get("remark") or "")] or meta
    log(f"[2] 探测 {len(pick)} 个出口（关键字 {only_kw}）")
    res = []
    with cf.ThreadPoolExecutor(max_workers=workers) as ex:
        for r in ex.map(one, pick):
            res.append(r)
    good = [r for r in res if r.get("ip") and r.get("cf_pass")]
    for r in res:
        if r.get("ip"):
            log(f"    {r['port']} {str(r.get('ip')):<18} {r.get('country')} "
                f"auth={r.get('auth')} cf={'PASS' if r.get('cf_pass') else 'BLOCK'} "
                f"{str(r.get('isp') or '')[:24]:<24}{r['remark'][:34]}")
    log(f"[2] 活 {len([r for r in res if r.get('ip')])}  过 CF {len(good)}")
    return good


# ---------------------------------------------------------------- 3. 邮箱
def pick_emails(limit: int = 6) -> list[dict]:
    sys.path.insert(0, str(REPO / "upstreams" / "gpt-register"))
    from core.outlook_client import (OutlookAccount, _ms_access_token, _ms_http,
                                     _fetch_via_graph_direct)
    B = pathlib.Path(r"D:\xi\msa-mail-tool")
    s = new_session()
    cards = s.get(f"{MAILTOOL}/api/cards", timeout=180).json().get("cards") or []
    cred = {}
    for line in (B / "cards.txt").read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "----" not in line:
            continue
        p = [x.strip() for x in line.split("----")]
        if len(p) >= 4:
            cred[p[0]] = (p[1], p[2], p[3])
    OA = re.compile(r"openai|chatgpt", re.I)
    cands = []
    for c in cards:
        em = str(c.get("email") or "")
        if c.get("used") or c.get("disabled"):
            continue
        if not em.lower().endswith(("@outlook.com", "@hotmail.com")):
            continue
        if str(c.get("type") or "").upper() != "GRAPH":
            continue
        cr = cred.get(em)
        if not cr or not cr[1]:
            continue
        cands.append({"email": em, "password": cr[0], "refresh_token": cr[1],
                      "client_id": c.get("client_id") or cr[2]})
    log(f"[3] 候选邮箱 {len(cands)}")

    def check(c):
        acc = OutlookAccount(c["email"], c["password"], c["client_id"], c["refresh_token"])
        o = dict(c)
        try:
            _ms_access_token(acc, _ms_http())
            msgs = _fetch_via_graph_direct(acc)
        except Exception:
            return None
        o["oa"] = any(OA.search(str(m.get("from") or "") + str(m.get("subject") or ""))
                      for m in msgs or [])
        return o

    virgin = []
    with cf.ThreadPoolExecutor(max_workers=8) as ex:
        for r in ex.map(check, cands):
            if r and not r["oa"]:
                virgin.append(r)
    log(f"[3] OpenAI 处女邮箱 {len(virgin)}")
    for v in virgin[:10]:
        log(f"    {v['email']}")
    return virgin[:limit]


# ---------------------------------------------------------------- 4/5. 注册
def register(email: str, proxy: str, turb_dir: pathlib.Path):
    sys.path.insert(0, str(turb_dir))
    import logging
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    import main as turb_main
    from core import db
    from core.name_samples import random_display_name
    from core.profile_utils import generate_random_birthday
    before = len(db.list_accounts(limit=50))
    try:
        turb_main.run_registration(email=email, name=random_display_name(),
                                   birthday=generate_random_birthday(), proxy=proxy)
    except Exception as e:
        log(f"    异常: {type(e).__name__}: {str(e)[:200]}")
    after = len(db.list_accounts(limit=50))
    return after > before


def import_to_pool(turb_dir: pathlib.Path) -> list[str]:
    s = new_session()
    s.headers.update(TURB_AUTH)
    r = s.get(f"{TURB}/api/accounts", timeout=30)
    # turb WebUI 没有列表接口，用 DB 直读
    sys.path.insert(0, str(turb_dir))
    from core import db
    accs = db.list_accounts(limit=50)
    payloads = []
    for a in accs:
        p = a.get("payload") or a
        if p.get("email") and p.get("access_token") and p.get("refresh_token"):
            payloads.append({
                "access_token": p.get("access_token"), "refresh_token": p.get("refresh_token"),
                "id_token": p.get("id_token") or "", "email": p.get("email"),
                "user_id": p.get("user_id"), "type": p.get("plan_type") or "free",
                "source_type": "oauth_login", "status": "正常",
                "created_at": p.get("created_at")})
    if not payloads:
        return []
    r = s.post(f"{OMNI}/api/accounts", json={"accounts": payloads}, headers=OMNI_AUTH, timeout=180)
    log(f"[5] 导入主池 -> {r.status_code} {r.text[:200]}")
    return [p["email"] for p in payloads]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=r"D:\tmp\vvout")
    ap.add_argument("--base-port", type=int, default=29100)
    ap.add_argument("--email-filter", default="", help="只用某个 VVCloud 账号的订阅")
    ap.add_argument("--skip-gen", action="store_true")
    ap.add_argument("--max-attempts", type=int, default=4)
    args = ap.parse_args()

    out = pathlib.Path(args.out)
    turb_dir = REPO / "upstreams" / "gpt-register"

    if args.skip_gen and (out / "ports.json").exists():
        meta = json.loads((out / "ports.json").read_text(encoding="utf-8"))
        log(f"[1] 复用已有出口 {len(meta)} 个")
    else:
        meta = gen_outlets(out, args.base_port, args.email_filter)
        start_mihomo(out)

    good = probe(meta)
    if not good:
        log("[2] 没有过 CF 的出口，退出（VVCloud 试用流量可能已耗尽，等限流窗口过去再跑）")
        return 2

    s = new_session()
    s.headers.update(TURB_AUTH)
    pool = "\n".join(f"http://127.0.0.1:{m['port']}" for m in good)
    s.post(f"{TURB}/api/config", json={"updates": {
        "PROXY_POOL": pool, "PROXY_POOL_UPSTREAM_PROXY": "",
        "OUTLOOK_FETCH_MODE": "graph", "USE_EMAIL_SERVICE": "True",
        "EMAIL_SOURCE": "outlook", "REGISTRATION_DRIVER": "protocol"}}, timeout=60)
    log(f"[4] PROXY_POOL 已写入 turb（{len(good)} 条）")

    virgin = pick_emails()
    if not virgin:
        log("[3] 没有可用的处女邮箱，退出（需要先补 Outlook 账号）")
        return 3

    text = "\n".join("----".join([v["email"], v["password"], v["client_id"], v["refresh_token"]])
                     for v in virgin)
    r = s.post(f"{TURB}/api/outlook/import", json={"source": "outlook", "text": text}, timeout=180)
    log(f"[4] 邮箱导入 -> {r.status_code} {r.text[:160]}")

    ok_emails = []
    for v in virgin[:args.max_attempts]:
        for m in good[:3]:
            log(f"[4] 注册 {v['email']} via {m['port']} ({m.get('remark')})")
            if register(v["email"], f"http://127.0.0.1:{m['port']}", turb_dir):
                ok_emails.append(v["email"])
                break
        if ok_emails:
            break

    emails = import_to_pool(turb_dir)
    log(f"[5] 主池账号: {emails}")
    return 0 if ok_emails else 4


if __name__ == "__main__":
    raise SystemExit(main())
