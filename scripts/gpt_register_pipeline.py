"""GPT 自动注册一键流水线（住宅出口 + 处女邮箱 -> turb 协议注册 -> 导入 omni2api 主池）。

链路
----
1. 从「站点注册控制台」(19879) 拉所有 VVCloud 试用账号的订阅 -> mihomo 多出口
   （必须用 UA v2rayN/6.0，否则机场返回的是示例密码，握手必被 RST）
2. 探测出口：出口 IP / 归属 / 能否打 chatgpt.com / **能否过 auth.openai.com 的 CF 校验**
3. 从「邮箱验证码管理工具」(19878) 挑 OpenAI 处女 Outlook 邮箱
4. 把邮箱与出口池写进 turb，跑 turb 协议注册（新版免密流程）
5. 注册成功的账号导入 omni2api 主号池并做一次真实对话验证

用法
----
    python scripts/gpt_register_pipeline.py --out D:\\tmp\\vvout --base-port 29100
    python scripts/gpt_register_pipeline.py --skip-gen --dir D:\\tmp\\vvout   # 复用已有出口
"""
